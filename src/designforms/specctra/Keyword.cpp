KeywordRegistry& KeywordRegistry::instance()
{
    static KeywordRegistry instance;
    return instance;
}

const Keyword* KeywordRegistry::find(const std::string& p_name) const
{
    auto it = keywords_.find(p_name);
    if (it != keywords_.end())
    {
        return it->second;
    }
    return nullptr;
}

void KeywordRegistry::register_keyword(const std::string& p_name, const Keyword* p_keyword)
{
    keywords_[p_name] = p_keyword;
}

