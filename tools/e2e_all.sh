#!/usr/bin/env bash
# Run tools/e2e_compare.sh over the boards of test_java_boards.sh and rewrite
# docs/migration/E2E_STATUS.md. Environment variables are passed through to e2e_compare.sh
# (E2E_TIMEOUT, E2E_OUT_DIR, FREEROUTING, JAVA_SES_DIR).
#
# Usage: tools/e2e_all.sh [board.dsn ...]   (default: the BOARDS list of test_java_boards.sh)
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
STATUS_MD="$ROOT/docs/migration/E2E_STATUS.md"

if [[ $# -gt 0 ]]; then
  BOARDS=("$@")
else
  # Single source for the board list: the BOARDS=( ... ) array of test_java_boards.sh.
  mapfile -t BOARDS < <(sed -n '/^BOARDS=(/,/^)/p' "$ROOT/test_java_boards.sh" | grep -o '"[^"]*\.dsn"' | tr -d '"')
fi

rows=()
for board in "${BOARDS[@]}"; do
  dsn="$board"
  [[ -f "$dsn" ]] || dsn="$ROOT/tests/data/$board"
  row="$("$SCRIPT_DIR/e2e_compare.sh" "$dsn")"
  echo "$row"
  rows+=("$row")
done

{
  echo "# E2E Status — C++ vs Java SES"
  echo
  echo "Generated by \`tools/e2e_all.sh\` on $(date +%Y-%m-%d) at commit $(git -C "$ROOT" rev-parse --short HEAD 2>/dev/null || echo unknown)."
  echo "Timeout per board: ${E2E_TIMEOUT:-300}s. Wire/via counts are taken inside \`(network_out\`;"
  echo "Java baselines come from \`java_output_ses/<board>_java.ses\` (\`./test_java_boards.sh\`), \"n/a\" = missing."
  echo
  echo "| Board | Status | Exit | Seconds | C++ wires | Java wires | C++ vias | Java vias |"
  echo "|-------|--------|------|---------|-----------|------------|----------|-----------|"
  for row in "${rows[@]}"; do
    echo "| $row |"
  done
} >"$STATUS_MD"

echo "wrote $STATUS_MD"
